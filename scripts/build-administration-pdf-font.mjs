// Writes the pinned Roboto bytes used by administration PDF exports.
// The source is the font already shipped by the pinned pdfme engine; its hash
// must match packages/templates/font-coverage.json. `--check` fails on drift.
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { getDefaultFont } from "@pdfme/common";

const root = new URL("../", import.meta.url);
const target = new URL("apps/api/src/administration-pdf-font-data.ts", root);
const coverage = JSON.parse(
  await readFile(
    new URL("packages/templates/font-coverage.json", root),
    "utf8",
  ),
);
const data = Object.values(getDefaultFont())[0].data;
const bytes =
  typeof data === "string"
    ? Buffer.from(data.replace(/^data:[^,]*,/, ""), "base64")
    : Buffer.from(data);
const sha256 = createHash("sha256").update(bytes).digest("hex");
if (sha256 !== coverage.fontSha256)
  throw new Error("ADMINISTRATION_PDF_FONT_HASH_MISMATCH");
const source = `// Generated by scripts/build-administration-pdf-font.mjs; do not edit.
// Roboto Regular from the pinned pdfme ${coverage.engineVersion} engine (Apache 2.0, see
// packages/templates/licenses/Roboto-Apache-2.0.txt). Loaded only by PDF exports
// whose text needs characters outside the standard WinAnsi fonts.
export const ADMINISTRATION_PDF_FONT_SHA256 = "${sha256}";
export const ADMINISTRATION_PDF_FONT_CODE_POINTS: readonly number[] = ${JSON.stringify(coverage.codePoints)};
export const ADMINISTRATION_PDF_FONT_BASE64 =
  "${bytes.toString("base64")}";
`;
if (process.argv.includes("--check")) {
  const current = await readFile(target, "utf8").catch(() => "");
  if (current !== source)
    throw new Error(
      "Administration PDF font data is stale. Run node scripts/build-administration-pdf-font.mjs.",
    );
  console.log(`Administration PDF font verified: ${sha256}.`);
} else {
  await writeFile(target, source);
  console.log(
    `Administration PDF font written: ${bytes.length} bytes, ${sha256}.`,
  );
}
