/** Build the email-sized edition of Guteneo's founding postmark.
 * Run with: node scripts/build-email-postmark.mjs
 * Type is outlined with the project's fonts so the imprint does not depend on
 * a workstation font or any resources loaded when the email is opened.
 */
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import * as fontkit from "fontkit";
import sharp from "sharp";

const root = new URL("../", import.meta.url);
const local = (path) => new URL(path, root);
const digest = (bytes) => createHash("sha256").update(bytes).digest("hex");
const sans = fontkit.openSync(
  fileURLToPath(local("apps/status/public/assets/plex-semibold.woff2")),
);
const mono = fontkit.openSync(
  fileURLToPath(local("videos/guteneo-film/public/fonts/mono.woff2")),
);
const source = "apps/web/public/brand/guteneo-portrait.png";
const portrait = await readFile(local(source));

// Lay out the actual glyph outlines on straight or circular baselines. On the
// lower arc the baseline travels in the opposite direction so it reads upright.
function lettering(font, label, size, spacing, position) {
  const scale = size / font.unitsPerEm;
  const { glyphs, positions } = font.layout(label);
  const widths = positions.map(({ xAdvance }) => xAdvance * scale);
  const length =
    widths.reduce((a, b) => a + b, 0) + spacing * (glyphs.length - 1);
  let pen = -length / 2;
  return glyphs
    .map((glyph, index) => {
      const width = widths[index];
      const [x, y, angle] = position(pen + width / 2);
      pen += width + spacing;
      return `<path transform="translate(${x.toFixed(3)} ${y.toFixed(3)}) rotate(${angle.toFixed(3)}) translate(${(-width / 2).toFixed(3)} 0) scale(${scale} ${-scale})" d="${glyph.path.toSVG()}"/>`;
    })
    .join("");
}
const arc = (radius, side) => (offset) => {
  const angle = offset / radius;
  return [
    radius * Math.sin(angle),
    side * radius * Math.cos(angle),
    (-side * angle * 180) / Math.PI,
  ];
};
const line = (baseline) => (offset) => [offset, baseline, 0];

// The tiny knockouts mark the ink only. The teeth and white paper belong to
// the original stamp, and the seal has no disc behind it.
const svg = `<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="384" height="210" viewBox="0 0 128 70">
<defs>
  <pattern id="dry-ink" width="6.1" height="5.7" patternUnits="userSpaceOnUse" patternTransform="rotate(19)">
    <rect width="6.1" height="5.7" fill="white"/><ellipse cx="1.4" cy="1.1" rx=".38" ry=".18" fill="black"/><circle cx="4.1" cy="3.7" r=".18" fill="black"/>
  </pattern>
  <mask id="impression" maskUnits="userSpaceOnUse" x="0" y="0" width="128" height="70"><rect width="128" height="70" fill="url(#dry-ink)"/></mask>
</defs>
<g transform="rotate(7 95 34)">
  <rect x="72.88" y="11.88" width="44.24" height="44.24" fill="white"/>
  <image x="67" y="6" width="56" height="56" xlink:href="data:image/png;base64,${portrait.toString("base64")}"/>
</g>
<g mask="url(#impression)" opacity=".87" fill="#30384b" stroke="#30384b">
  <g transform="rotate(-7 36 39)" fill="none" stroke-width=".86" stroke-linecap="round">
    <path d="M2 31c6-5 10 4 16 0s10-4 14-1 M1 36c6-5 10 4 16 0s10-4 14-1 M1 41c6-5 10 4 16 0s10-4 14-1 M2 46c6-5 10 4 16 0s10-4 14-1"/>
  </g>
  <g transform="translate(57 39) rotate(-12)">
    <g fill="none">
      <circle r="26.4" stroke-width="1.25"/><circle r="24.5" stroke-width=".45"/>
      <path d="M-16.7 -5.4H16.7 M-16.7 5.4H16.7" stroke-width=".75"/>
    </g>
    <g stroke="none">
      ${lettering(sans, "LUXEMBOURG", 6.1, 0.51, arc(17.5, -1))}
      ${lettering(sans, "PREMIER JOUR", 4.9, 0.42, arc(21.1, 1))}
      ${lettering(mono, "16.09.26", 6.65, 0.08, line(2.32))}
      <path d="m-20 -1.6 1.6 1.6-1.6 1.6-1.6-1.6z M20 -1.6 21.6 0 20 1.6 18.4 0z"/>
    </g>
  </g>
</g></svg>`;
const png = await sharp(Buffer.from(svg), { density: 288 })
  .resize(384, 210)
  .png({ palette: true, colours: 256, dither: 0.45, effort: 10 })
  .toBuffer();
const sha256 = digest(png);
const filename = `guteneo-email-postmark-${sha256.slice(0, 16)}.png`;
const asset = {
  sha256,
  cid: `guteneo-postmark.${sha256}@guteneo.com`,
  filename,
  bytes: png.length,
  width: 384,
  height: 210,
  displayWidth: 128,
  displayHeight: 70,
};
const json = (value) => JSON.stringify(value, null, 2) + "\n";
const output = `apps/web/public/brand/${filename}`;
await writeFile(local(output), png);
await writeFile(
  local("packages/contracts/src/email-branding-current.json"),
  json(asset),
);
await writeFile(
  local("packages/contracts/src/email-branding-image.ts"),
  `/** Generated by scripts/build-email-postmark.mjs from the approved artwork. */\nexport const EMAIL_BRAND_IMAGE_BASE64 =\n  "${png.toString("base64")}";\n`,
);
await writeFile(
  local("assets/brand/source/guteneo-email-postmark-proof.json"),
  json({
    source,
    sourceSha256: digest(portrait),
    output,
    ...asset,
    imprint:
      "Email adaptation of the Luxembourg first-day seal in PublicFooterStamp, apps/web/src/public-chrome.tsx. The historic issue date is decorative and is independent of the message.",
    paper:
      "10.5% inset on each side of the framed portrait, with transparent outer teeth.",
    generator: "scripts/build-email-postmark.mjs",
  }),
);
console.log(`${output} (${png.length} bytes)`);
